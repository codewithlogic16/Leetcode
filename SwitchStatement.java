import java.util.*;
public class SwitchStatement {
      public static void main(String args []){
            int number = 2;
            switch (number) {
                  case 1:
                  System.out.println("ankit");
                  break;
                  case 2:
                  System.out.println("rauneet");
                  break;
                  case 3:
                  System.out.println("arnav");
                  break;
                  case 4:
                  System.out.println("ayush");
                  break;
                  default:
                  System.out.println("WE WAKE UP");
            }
      }
}